function toISO(dStr) {
  const [d, m, y] = dStr.split('/');
  return `${y}-${m}-${d}`;
}

async function main() {
  // Buscar todas as saídas ordenadas por data_hora e depois por id
  const { data: saidas, error } = await supabase
    .from('abastecimentos')
    .select('id, data_hora')
    .order('data_hora', { ascending: true })
    .order('id', { ascending: true });

  if (error) {
    console.error('Erro ao buscar saídas:', error);
    process.exit(1);
  }

  console.log(`Total de saídas no banco: ${saidas.length}`);
  console.log(`Total de datas fornecidas: ${datas.length}`);

  if (datas.length > saidas.length) {
    console.error(`ERRO: Mais datas (${datas.length}) do que saídas (${saidas.length})`);
    process.exit(1);
  }

  // Mostra primeiros e últimos para conferência
  console.log(`\nPrimeira saída: id=${saidas[0].id}, data_hora=${saidas[0].data_hora} -> nova data: ${toISO(datas[0])}`);
  console.log(`Última a atualizar: id=${saidas[datas.length-1].id}, data_hora=${saidas[datas.length-1].data_hora} -> nova data: ${toISO(datas[datas.length-1])}`);

  let updated = 0;
  let errors = 0;

  for (let i = 0; i < datas.length; i++) {
    const saida = saidas[i];
    const novaData = toISO(datas[i]);
    const horaExistente = saida.data_hora ? saida.data_hora.split('T')[1] || '00:00:00' : '00:00:00';
    const novaDataHora = `${novaData}T${horaExistente}`;

    const { error: updateError } = await supabase
      .from('abastecimentos')
      .update({ data_hora: novaDataHora })
      .eq('id', saida.id);

    if (updateError) {
      console.error(`Erro saída ${i + 1} (${saida.id}):`, updateError.message);
      errors++;
    } else {
      updated++;
    }

    if ((i + 1) % 50 === 0) console.log(`  ${i + 1}/${datas.length} processadas...`);
  }

  console.log(`\nResultado: ${updated} atualizadas, ${errors} erros`);
}

main();
